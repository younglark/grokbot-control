// Pack the real public workspace and install outside this repository (no workspace resolution).
import {mkdtempSync,writeFileSync,readFileSync,mkdirSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
import assert from 'node:assert/strict';
import {lastJsonValue} from './npm-pack-json.mjs';
const repo=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const sandbox=mkdtempSync(join(tmpdir(),'gbc-independent-consumer-'));
const npm=process.env.npm_execpath;
assert.ok(npm,'Run this check through npm run verify:package');
const runNpm=(args,cwd=repo,env=process.env)=>execFileSync(process.execPath,[npm,...args],{cwd,env,encoding:'utf8',timeout:180000,maxBuffer:8*1024*1024});
// prepack may print tsc/vite logs on stdout before npm pack --json.
const packed=lastJsonValue(runNpm(['pack','-w','grokbot-control','--json','--pack-destination',sandbox]))[0];
const expected=JSON.parse(readFileSync(join(repo,'packages/grokbot-control/package.json'),'utf8'));
assert.equal(packed.name,'grokbot-control');assert.equal(packed.version,expected.version);
for(const file of packed.files)assert.match(file.path,/^(dist\/|vendor\/proto-gen\/|README\.md$|package\.json$|web\/SHADCN-LICENSE\.txt$|web\/REGISTRY\.md$)/,`Unexpected publish file: ${file.path}`);
const consumer=join(sandbox,'consumer');mkdirSync(consumer);
writeFileSync(join(consumer,'package.json'),JSON.stringify({name:'independent-package-verification',private:true,type:'module'}));
const home=join(sandbox,'home');mkdirSync(home);
const env={PATH:process.env.PATH,HOME:home,TMPDIR:tmpdir(),GBT_MOCK:'1',GBT_CREDENTIALS_DIR:join(home,'synthetic-credentials')};
if(process.env.SystemRoot)env.SystemRoot=process.env.SystemRoot;
const install=runNpm(['install','--omit=dev','--no-audit','--no-fund',join(sandbox,packed.filename)],consumer,env);
const pkg=JSON.parse(readFileSync(join(consumer,'node_modules/grokbot-control/package.json'),'utf8'));
assert.equal(pkg.name,'grokbot-control');assert.equal(pkg.version,expected.version);
assert.equal(pkg.bin.gbc,'./dist/cli/main.js');assert.equal(pkg.bin['gbc-mcp'],'./dist/mcp/main.js');
assert.ok(!pkg.scripts.prepare && !pkg.scripts.postinstall && !pkg.scripts.install,'Consumers must not compile/reach into workspace');
for(const value of Object.values(pkg.dependencies))assert.ok(!/^(workspace:|file:)/.test(value),'Unpublished workspace dependency');
const exec=(file,args=[],input='')=>execFileSync(process.execPath,[join(consumer,'node_modules/grokbot-control',file),...args],{cwd:consumer,env,input,encoding:'utf8',timeout:15000});
const help=runNpm(['exec','--offline','--','gbc','--help'],consumer,env);assert.match(help,/gbc|Grok/i);
// Preserve MCP's existing behavior: --help is not a human-help handler; closed stdin exits cleanly.
const mcpHelp=runNpm(['exec','--offline','--','gbc-mcp','--help'],consumer,env);
const initialize={jsonrpc:'2.0',id:1,method:'initialize',params:{protocolVersion:'2024-11-05',capabilities:{},clientInfo:{name:'isolated-package-check',version:'1'}}};
const mcp=exec('dist/mcp/main.js',['--mock'],JSON.stringify(initialize)+'\n');
assert.match(mcp,/grokbot-control/);
const sdk=execFileSync(process.execPath,['--input-type=module','-e',"import('grokbot-control').then(m=>{if(typeof m.ControlPlane!=='function'||typeof m.createGrokBotClient!=='function'||typeof m.SyncOps!=='function')throw Error('SDK exports missing');console.log('SDK_IMPORT_OK')})"],{cwd:consumer,env,encoding:'utf8',timeout:15000});
assert.match(sdk,/SDK_IMPORT_OK/);
const result={ok:true,sandbox,tarball:join(sandbox,packed.filename),files:packed.files.length,installedOutsideRepository:true,normalInstallLifecycle:true,noWorkspaceRuntimeDependency:true,gbcHelp:true,mcpHelp:{exit:0,humanHelpHandler:false,stdoutBytes:mcpHelp.length},mcpInitialize:true,sdkImport:true,prepareAbsent:true,installSummary:install.trim()};
writeFileSync(join(sandbox,'result.json'),JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result,null,2));
